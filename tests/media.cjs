const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../modules/media/script.js'), 'utf8');
let text = 'abcdef', visible = true, readonly = false, selection, inserted, saved = false;
const textarea = { id: 'wiki__text', value: text, isConnected: true, selectionStart: 1, selectionEnd: 3, scrollTop: 12, getClientRects: () => visible ? [{}] : [], focus() {}, setSelectionRange(a,b) { selection = [a,b]; }, setRangeText(t,a,b) { inserted = t; }, dispatchEvent() {} };
const context = { window: {}, document: { addEventListener() {}, getElementById: () => textarea, execCommand: () => false }, Event: class {} };
vm.runInNewContext(source, context);
const api = context.window.FokusButlerMedia;
const image = {id:'electronics:scope.png',image:true};
assert.equal(api.syntax(image, {caption:'Scope | {{trace}}\n', width:'640',align:'center',mode:'nolink'}), '{{ :electronics:scope.png?640&nolink|Scope     trace    }}');
assert.equal(api.syntax(image,{width:'-1',align:'inline'}), '{{:electronics:scope.png}}');
assert.equal(api.syntax(image,{width:'10?evil',align:'inline'}), '{{:electronics:scope.png}}');
assert.equal(api.syntax(image,{width:'200',mode:'linkonly',align:'inline'}), '{{:electronics:scope.png?linkonly}}');
assert.equal(api.syntax({id:'files:report.pdf',image:false},{caption:'Report',width:'200',mode:'nolink',align:'center'}), '{{:files:report.pdf?linkonly|Report}}');
const native = api.capture('wiki__text');
api.insert(native,'{{:image.png}}');
assert.deepEqual(selection,[1,3]); assert.equal(inserted,'{{:image.png}}');
textarea.value = 'changed'; assert.throws(()=>api.insert(native,'x'),/editor changed/); textarea.value=text;
visible=false; assert.equal(api.capture('wiki__text'),null);
const cm = {getTextArea:()=>textarea,getWrapperElement:()=>({getClientRects:()=>[{}]}),getOption:()=>readonly,getValue:()=>text,getCursor:which=>({ch:which==='from'?2:4}),indexFromPos:p=>p.ch,posFromIndex:ch=>({ch}),getScrollInfo:()=>({left:0,top:10}),focus(){},setSelection(a,b){selection=[a.ch,b.ch];},replaceSelection(t){inserted=t;},save(){saved=true;},scrollTo(){}};
context.window.plugin_codemirror={cm};
const code = api.capture('wiki__text'); api.insert(code,'{{:scope.png}}');
assert.deepEqual(selection,[2,4]); assert.equal(inserted,'{{:scope.png}}'); assert.equal(saved,true);
text='changed CodeMirror'; assert.throws(()=>api.insert(code,'x'),/editor changed/);
readonly=true; assert.equal(api.capture('wiki__text'),null);

assert.equal(api.sidebarWidth(1000, 0.18), 180);
assert.equal(api.sidebarWidth(1500, 0.18), 270, 'Sidebar scales with dialog width');
assert.equal(api.sidebarWidth(900, 1), 360, 'Resizing preserves room for media and details');
assert.equal(api.sidebarWidth(900, 0), 130, 'Sidebar keeps a usable minimum width');
let paneOpened, closed = false, prevented = false, stopped = false;
context.window.infinitepanelsOpenPage = (...args) => { paneOpened = args; };
const page = {id:'notes:scope',url:'http://wiki.test/notes:scope'};
const click = {button:0,preventDefault(){prevented=true;},stopPropagation(){stopped=true;}};
assert.equal(api.openReference(click,page,()=>{closed=true;}),true);
assert.deepEqual(paneOpened,[page.url,true,page.id]);
assert.equal(closed && prevented && stopped,true);
paneOpened=null;
assert.equal(api.openReference({...click,ctrlKey:true},page,()=>{}),false);
assert.equal(paneOpened,null,'Modified clicks keep browser navigation');
delete context.window.infinitepanelsOpenPage;
context.window.location={origin:'http://wiki.test'};
context.window.parent={location:{origin:'http://wiki.test'},infinitepanelsOpenPage:(...args)=>{paneOpened=args;}};
assert.equal(api.openReference(click,page,()=>{}),true);
assert.deepEqual(paneOpened,[page.url,true,page.id],'Editor iframes use the parent Fokus workspace');

console.log('PASS: media syntax, resize limits, native and CodeMirror insertion, stale-editor guards, and Fokus pane routing.');

const allowedNamespaces = new Set(['', 'drawings:schematics:power', 'images', 'drawings:scope']);
const branches = api.namespaceBranches(allowedNamespaces);
assert.deepEqual(Array.from(branches.get('')), ['drawings', 'images']);
assert.deepEqual(Array.from(branches.get('drawings')), ['drawings:schematics', 'drawings:scope']);
assert.deepEqual(Array.from(branches.get('drawings:schematics')), ['drawings:schematics:power']);
assert.equal(allowedNamespaces.has('drawings'), false, 'Structural ancestors do not grant browse or drop permissions');
console.log('PASS: nested namespace hierarchy preserves restricted structural ancestors.');
